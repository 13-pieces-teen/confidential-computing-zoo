#!/usr/bin/env python3
"""Build isolated experiment deployments; production has no weakening switch.

Rendering copies and modifies a private deployment package. Binary payloads
must come from the verified normal build; native SPIRE additionally builds its
own HCL merger. inspect verifies actual generated bytes, never just mode labels.
"""
import argparse
import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
AGENT_CC = HERE.parents[1]
WORKLOAD = AGENT_CC / "core/spire/workload"
HELPER = AGENT_CC / "core/spire/helpers/spiffe-helper"
VARIANTS = ("full_argus", "native_spire_guarded", "no_watchdog", "no_close", "static_mtls")
SHORT = dict(zip(VARIANTS, ("full", "native", "nowd", "noclose", "static")))
ARTIFACTS = ["bin/" + x for x in (
    "argus-tdx-nodeattestor-agent", "argus-tdx-nodeattestor-server", "argus-tdx-workloadattestor",
    "argus-workload", "spiffe-helper", "argus-agent-config", "spiffe-authz", "spiffe-mtls-probe",
    "spiffe-client-credentials", "argus-spire-evidence-provider")]
ARTIFACTS += ["spire-1.15.3/bin/spire-agent", "spire-1.15.3/bin/spire-server"]


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def write(path, content, executable=False):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    path.chmod(0o700 if executable else 0o600)


def json_write(path, value):
    write(path, json.dumps(value, indent=2, sort_keys=True) + "\n")


def load_module(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def replace_once(contents, before, after):
    if contents.count(before) != 1:
        raise ValueError("experiment transformation no longer matches production source: " + before[:100])
    return contents.replace(before, after, 1)


def _isolate(config, variant, experiment_id):
    if variant not in VARIANTS or not re.fullmatch(r"[a-z][a-z0-9-]{0,14}", experiment_id):
        raise ValueError("unknown variant or invalid experiment_id (lowercase, at most 15 characters)")
    c = copy.deepcopy(config)
    # Keep the approved Node identity and its durable data/proof-key paths. Arms
    # execute sequentially; identities below can never alias production targets.
    suffix = "/experiment/" + experiment_id + "/" + SHORT[variant]
    for key in ("helper_id", "target_id"):
        c["identity"][key] += suffix
    clients = c["identity"].pop("client_id", None)
    if clients is not None:
        if "allowed_client_ids" in c["identity"]:
            raise ValueError("client_id and allowed_client_ids are mutually exclusive")
        c["identity"]["allowed_client_ids"] = [clients]
    c["identity"]["allowed_client_ids"] = [s + suffix for s in c["identity"]["allowed_client_ids"]]
    root = "argus-experiments/" + experiment_id + "/" + variant
    c["paths"] = {"install_dir": "/opt/" + root + "/payload", "config_dir": "/etc/" + root,
                  "records_dir": "/var/log/" + root, "spire_bin_dir": "/opt/" + root + "/spire/bin",
                  "run_name": "ax-" + experiment_id + "-" + SHORT[variant]}
    c["server_config"] = c["paths"]["config_dir"] + "/environment.json"
    c["server_script"] = c["paths"]["install_dir"] + "/scripts/workload.py"
    return c


def _native_builder_source():
    text = (HELPER / "cmd/argus-agent-config/main.go").read_text(encoding="utf-8")
    text = replace_once(text,
        'if k != "WorkloadAttestor\\x00argus_tdx\\x00" && k != "WorkloadAttestor\\x00unix\\x00" {',
        'if k != "WorkloadAttestor\\x00docker\\x00" && k != "WorkloadAttestor\\x00unix\\x00" {')
    text = replace_once(text, '\top, err := block(oroot, "plugins")', '''	// Experimental native baseline: remove only the custom workload plugin.
	var kept []*ast.ObjectItem
	for _, item := range plugins.Items {
		if key(item) != "WorkloadAttestor\\x00argus_tdx\\x00" { kept = append(kept, item) }
	}
	plugins.Items = kept
	op, err := block(oroot, "plugins")''')
    return text


def _transform_package(package, c, variant, native_uid):
    # Rewrite only our service names, including all references and cleanup
    # commands. This also creates a dedicated NGINX unix user/group per arm.
    names = {old: c["paths"]["run_name"] + "-" + role for role, old in {
        "helper": "argus-helper", "nginx": "argus-nginx", "authz": "argus-authz",
        "agent": "argus-workload-agent", "provider": "argus-tdx-provider"}.items()}
    for folder in ("scripts", "config", "systemd"):
        for path in (package / folder).iterdir():
            if not path.is_file():
                continue
            contents = path.read_text(encoding="utf-8")
            for old, new in names.items():
                contents = contents.replace(old, new)
            write(path, contents, path.suffix == ".sh")
    for path in list((package / "systemd").glob("*.service")):
        new = names.get(path.stem)
        if new:
            path.rename(path.with_name(new + ".service"))
    helper_unit = package / "systemd" / (names["argus-helper"] + ".service")
    nginx_unit = package / "systemd" / (names["argus-nginx"] + ".service")
    if variant == "no_watchdog":
        text = helper_unit.read_text()
        for line in ("Environment=ARGUS_REQUIRE_SYSTEMD_WATCHDOG=1\n", "WatchdogSec=5s\n", "WatchdogSignal=SIGKILL\n"):
            text = replace_once(text, line, "")
        write(helper_unit, text)
    if variant == "no_close":
        text = replace_once(helper_unit.read_text(), "ExecStopPost=@BIN@/nginx-hook.sh stop\n", "")
        write(helper_unit, text)
        text = "\n".join(line for line in nginx_unit.read_text().splitlines()
                         if not line.startswith(("BindsTo=", "Requires=", "PartOf="))) + "\n"
        write(nginx_unit, text)
        hook = package / "scripts/nginx-hook.py"
        write(hook, replace_once(hook.read_text(),
              '    elif action == "stop":\n        run(["systemctl", "stop", d.unit("nginx")])',
              '    elif action == "stop":\n        pass  # Experiment only: credential cleanup still runs.'))
    runtime = package / "scripts/workload.py"
    text = runtime.read_text()
    if variant == "native_spire_guarded":
        start = text.index('    WorkloadAttestor "argus_tdx" {')
        end = text.index('    overlay = d.render(', start)
        text = text[:start] + '    WorkloadAttestor "docker" { plugin_data {} }\n}\n\'\'\'\n' + text[end:]
        before = '''    a = baseline(c)
    return {"argus_tdx:verified:true", "argus_tdx:workload_id:" + d.workload["id"],
            "argus_tdx:policy:" + a["policy_id"], "argus_tdx:agent_id:" + d.identity["agent_id"],
            "argus_tdx:image_config_digest:" + a["image_config_digest"],
            "argus_tdx:config_digest:" + a["config_digest"]}'''
        after = '''    a = baseline(c)
    return {"unix:uid:NATIVE_UID", "unix:path:" + a["executable"],
            "docker:image_config_digest:" + a["image_config_digest"],
            "docker:label:io.trucon.workload-id:" + d.workload["id"]}'''.replace("NATIVE_UID", str(native_uid))
        text = replace_once(text, before, after)
        text = replace_once(text, '"trustee_direct": direct_trustee(c)', '"trustee_direct": "NODE_ONLY_NO_WORKLOAD_APPRAISAL"')
        text = replace_once(text, '    appraisal = correlated_appraisal(journal, target, proof["server_serial"], invocation)',
                            '    appraisal = None  # Native SPIRE has no Workload EAR/log gate.')
        text = replace_once(text, '"evidence_kind": "COMPANY_REAL_TDX_RUN"',
                            '"evidence_kind": "NATIVE_SPIRE_LOCAL_GUARD_NO_WORKLOAD_APPRAISAL"')
    if variant == "static_mtls":
        # Static uses the same NGINX/AuthZ, namespace and application API keys.
        # No Helper/Agent/Provider participates in the measured path.
        text = replace_once(text, '\nif __name__ == "__main__":',
                            '\nfrom static_runtime import install_static\ninstall_static(globals())\n\nif __name__ == "__main__":')
        write(package / "scripts/static_runtime.py", (HERE / "static_runtime.py").read_text())
        write(nginx_unit, "\n".join(line for line in nginx_unit.read_text().splitlines()
              if not line.startswith(("BindsTo=", "After="))) + "\n")
        with_authz = nginx_unit.read_text().replace("[Service]", "Requires=" + names["argus-authz"] + ".service\nAfter=" + names["argus-authz"] + ".service\n\n[Service]")
        write(nginx_unit, with_authz)
        for path in list((package / "systemd").glob("*.service")):
            if path.name not in (nginx_unit.name, names["argus-authz"] + ".service"):
                path.unlink()
    write(runtime, text)
    # Ordinary install cannot activate an experimental package by accident.
    installer = package / "scripts/install.sh"
    write(installer, replace_once(installer.read_text(), "set -euo pipefail\n",
        'set -euo pipefail\n[[ "${ARGUS_EXPERIMENT_INSTALL:-}" == "' + variant + '" ]] || { echo "use variants.py install --execute-experiment" >&2; exit 1; }\n'), True)
    return {role: names[old] for role, old in {"helper": "argus-helper", "nginx": "argus-nginx",
            "authz": "argus-authz", "agent": "argus-workload-agent", "provider": "argus-tdx-provider"}.items()}


def render_variant(config, variant, output, *, experiment_id, build_dir=None, native_uid=0,
                   static_credentials=None, compile_native=True):
    """Return manifest for an immutable package. Without build_dir: source only.

    build_dir is a complete verified Linux workload build; native additionally
    needs Go. static_credentials maps cert/key/bundle to protected Linux paths.
    Source-only packages are inspectable but cannot install or claim runnable.
    """
    if type(native_uid) is not int or native_uid < 0:
        raise ValueError("native_uid must be a nonnegative integer")
    config = json.loads(Path(config).read_text()) if isinstance(config, (str, Path)) else config
    sys.path.insert(0, str(WORKLOAD / "scripts"))
    try:
        from deployment import Deployment
        Deployment(config)
        c = _isolate(config, variant, experiment_id)
        d = Deployment(c)
    finally:
        sys.path.pop(0)
    if not config.get("approved_policy_artifact"):
        raise ValueError("experiments require the explicit existing approved_policy_artifact; no default policy change")
    if variant == "static_mtls":
        if not isinstance(static_credentials, dict) or set(static_credentials) != {"cert", "key", "bundle"}:
            raise ValueError("static_mtls requires dedicated static_credentials file references")
        from deployment import linux_path
        for value in static_credentials.values():
            linux_path(value)
    elif static_credentials is not None:
        raise ValueError("static_credentials is only valid for static_mtls")
    output = Path(output).resolve()
    if output.exists():
        raise ValueError("output already exists; do not overwrite experiment evidence")
    output.mkdir(parents=True, mode=0o700)
    package = output / "package"
    for folder in ("scripts", "config", "systemd", "policy"):
        shutil.copytree(WORKLOAD / folder, package / folder, ignore=shutil.ignore_patterns("__pycache__"))
    units = _transform_package(package, c, variant, native_uid)
    json_write(output / "environment.json", c)
    if static_credentials:
        json_write(package / "config/static-credentials.json", static_credentials)
    source_builder = output / "native-config-builder.go"
    if variant == "native_spire_guarded":
        write(source_builder, _native_builder_source())
    payload_ready = False
    if build_dir is not None:
        build_dir = Path(build_dir)
        provenance = load_module("variant_build_provenance", WORKLOAD / "scripts/build_manifest.py")
        original = json.loads((build_dir / "build-manifest.json").read_text())
        provenance.verify(WORKLOAD, build_dir, original, ARTIFACTS)
        for name in ARTIFACTS:
            dest = output / "build" / name
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(build_dir / name, dest)
            dest.chmod(0o755)
        if variant == "native_spire_guarded" and compile_native:
            env = dict(os.environ, GOOS="linux", GOARCH="amd64")
            subprocess.run(["go", "build", "-trimpath", "-o", str(output / "build/bin/argus-agent-config"),
                            str(source_builder)], cwd=HELPER, env=env, check=True, timeout=300)
        if variant != "native_spire_guarded" or compile_native:
            derived = copy.deepcopy(original)
            derived["base_build_manifest_sha256"] = sha(build_dir / "build-manifest.json")
            derived["experiment_variant"] = variant
            derived["artifacts"] = {name: sha(output / "build" / name) for name in ARTIFACTS}
            derived["installed_sources"] = {p.relative_to(package).as_posix(): sha(p) for p in provenance.installed_sources(package)}
            derived["build_inputs"] = {p.relative_to(package).as_posix(): sha(p) for p in provenance.build_inputs(package)}
            json_write(output / "build/build-manifest.json", derived)
            write(output / "build/SHA256SUMS", "".join(derived["artifacts"][name] + "  " + name + "\n" for name in ARTIFACTS))
            payload_ready = True
    # Render previews without writing any system /run, /etc or /opt paths.
    for path in (package / "systemd").glob("*.service"):
        write(output / "effective" / path.name, d.render(path.read_text()))
    for name in ("helper.conf", "nginx.conf"):
        write(output / "effective" / name, d.render((package / "config" / name).read_text()))
    manifest = {"schema_version": 1, "variant": variant, "experiment_id": experiment_id,
                "payload_ready": payload_ready, "remote_acceptance": "NOT_RUN", "config": c,
                "units": units, "native_uid": native_uid,
                "node_data": "PRESERVED_SEQUENTIAL_ARMS", "source_config_sha256": hashlib.sha256(json.dumps(config, sort_keys=True).encode()).hexdigest(),
                "files": {p.relative_to(output).as_posix(): sha(p) for p in sorted(output.rglob("*")) if p.is_file()}}
    json_write(output / "variant.json", manifest)
    inspect_variant(output)
    return manifest


def _unit_directives(text):
    result = {}
    for line in text.splitlines():
        if "=" in line and not line.startswith(("#", ";")):
            key, value = line.split("=", 1)
            result.setdefault(key.strip(), []).append(value.strip())
    return result


def inspect_variant(output, *, live=False):
    """Verify sealed files and effective systemd on demand; return evidence."""
    output = Path(output).resolve()
    manifest = json.loads((output / "variant.json").read_text())
    variant = manifest["variant"]
    if variant not in VARIANTS or manifest.get("schema_version") != 1:
        raise ValueError("invalid experiment manifest")
    for name, expected in manifest["files"].items():
        path = output / name
        if Path(name).is_absolute() or ".." in Path(name).parts or path.is_symlink() or not path.is_file() or sha(path) != expected:
            raise ValueError("experiment artifact changed: " + name)
    actual = {p.relative_to(output).as_posix() for p in output.rglob("*") if p.is_file() and p.name != "variant.json"}
    if actual != set(manifest["files"]):
        raise ValueError("unlisted experiment artifact")
    c = json.loads((output / "environment.json").read_text())
    if c != manifest["config"]:
        raise ValueError("experiment configuration mismatch")
    units = manifest["units"]
    directory = output / "effective"
    helper = _unit_directives((directory / (units["helper"] + ".service")).read_text()) if variant != "static_mtls" else {}
    nginx = _unit_directives((directory / (units["nginx"] + ".service")).read_text())
    hook = (output / "package/scripts/nginx-hook.py").read_text()
    if variant == "no_watchdog":
        if "WatchdogSec" in helper or any("ARGUS_REQUIRE_SYSTEMD_WATCHDOG" in v for v in helper.get("Environment", [])):
            raise ValueError("no_watchdog still enables external watchdog")
    elif variant != "static_mtls" and helper.get("WatchdogSec") != ["5s"]:
        raise ValueError("guarded variant lost watchdog")
    if variant == "no_close":
        if any(k in nginx for k in ("BindsTo", "Requires", "PartOf")) or any(v.endswith(" stop") for v in helper.get("ExecStopPost", [])) or 'run(["systemctl", "stop", d.unit("nginx")])' in hook:
            raise ValueError("no_close retains an active ingress close path")
        if not any(v.endswith(" clear") for v in helper.get("ExecStopPost", [])):
            raise ValueError("no_close must retain credential cleanup")
    elif variant != "static_mtls" and (not nginx.get("BindsTo") or not any(v.endswith(" stop") for v in helper.get("ExecStopPost", []))):
        raise ValueError("guarded variant lost active ingress closure")
    runtime = (output / "package/scripts/workload.py").read_text()
    if variant == "native_spire_guarded":
        if 'WorkloadAttestor "argus_tdx"' in runtime or 'WorkloadAttestor "docker"' not in runtime or 'return {"argus_tdx:verified:true"' in runtime:
            raise ValueError("native baseline still includes custom Workload attestation")
    report = {"schema_version": 1, "variant": variant, "artifact_integrity": "PASS",
              "effective_config": "PASS", "payload_ready": manifest["payload_ready"], "live": "NOT_RUN"}
    if live:
        if sys.platform != "linux" or os.geteuid() != 0:
            raise ValueError("live inspection requires root on Linux")
        active_roles = ("authz", "nginx") if variant == "static_mtls" else tuple(units)
        observed = {}
        for role in active_roles:
            unit = units[role] + ".service"
            fragment = Path(subprocess.check_output(["systemctl", "show", unit, "-p", "FragmentPath", "--value"], text=True).strip())
            if not fragment.is_file() or fragment.read_bytes() != (directory / unit).read_bytes():
                raise ValueError("installed unit differs: " + unit)
            raw = subprocess.check_output(["systemctl", "show", unit, "-p", "DropInPaths", "-p", "WatchdogUSec", "-p", "BindsTo", "-p", "Requires", "-p", "PartOf", "-p", "ExecStopPost", "-p", "Environment"], text=True)
            values = dict(line.split("=", 1) for line in raw.splitlines() if "=" in line)
            if values.get("DropInPaths"):
                raise ValueError("unreviewed systemd drop-in changes experiment: " + unit)
            if role == "helper" and ((variant == "no_watchdog") != (values.get("WatchdogUSec") == "0")):
                raise ValueError("effective watchdog differs from experiment")
            if role == "nginx" and variant == "no_close" and any(units["helper"] in values.get(k, "") or units["authz"] in values.get(k, "") for k in ("BindsTo", "Requires", "PartOf")):
                raise ValueError("effective NGINX dependency reinstates close")
            observed[unit] = values
        install = Path(c["paths"]["install_dir"])
        for folder in ("scripts", "config", "policy", "systemd"):
            for path in (output / "package" / folder).iterdir():
                if path.is_file() and (folder != "scripts" or path.suffix == ".py" or path.name == "nginx-hook.sh"):
                    installed = install / folder / path.name
                    if not installed.is_file() or sha(installed) != sha(path):
                        raise ValueError("installed source differs: " + str(installed))
        for name in ARTIFACTS:
            installed = install / name if name.startswith("bin/") else Path(c["paths"]["spire_bin_dir"]) / Path(name).name
            if not installed.is_file() or sha(installed) != sha(output / "build" / name):
                raise ValueError("installed binary differs: " + name)
        for name in ("helper.conf", "nginx.conf"):
            installed = Path(c["paths"]["config_dir"]) / name
            if not installed.is_file() or installed.read_bytes() != (directory / name).read_bytes():
                raise ValueError("installed rendered configuration differs: " + name)
        if variant != "static_mtls":
            # Re-run the checked merger against the current protected Node
            # source into a temporary file; never trust a runtime mode label.
            overlay = Path(c["paths"]["config_dir"]) / "agent-overlay.conf"
            overlay_text = overlay.read_text()
            if variant == "native_spire_guarded":
                if 'WorkloadAttestor "argus_tdx"' in overlay_text or 'WorkloadAttestor "docker"' not in overlay_text:
                    raise ValueError("effective native overlay differs")
            elif 'WorkloadAttestor "argus_tdx"' not in overlay_text:
                raise ValueError("effective Argus overlay lost Workload attestation")
            for exact in (c["identity"]["helper_id"], "/run/" + c["paths"]["run_name"] + "-spire-broker/broker.sock"):
                if json.dumps(exact) not in overlay_text:
                    raise ValueError("effective Broker overlay identity/path differs")
            with tempfile.TemporaryDirectory(prefix="argus-variant-inspect-") as temporary:
                expected = Path(temporary) / "agent.conf"
                subprocess.run([str(install / "bin/argus-agent-config"), "-source", c["node_agent_config"],
                    "-overlay", str(overlay), "-node-binary", str(install / "bin/argus-tdx-nodeattestor-agent"),
                    "-output", str(expected), "-trust-domain", c["identity"]["trust_domain"],
                    "-agent-id", c["identity"]["agent_id"], "-evidence-socket", "/run/" + c["paths"]["run_name"] + "/evidence-provider.sock"], check=True, timeout=30)
                if expected.read_bytes() != (Path(c["paths"]["config_dir"]) / "agent.conf").read_bytes():
                    raise ValueError("effective Agent configuration differs from verified merger output")
        report.update(live="PASS", systemd=observed)
    return report


def install_variant(output, *, execute_experiment=False):
    output = Path(output).resolve()
    result = inspect_variant(output)
    if not execute_experiment or sys.platform != "linux" or os.geteuid() != 0:
        raise ValueError("installation requires Linux root and --execute-experiment")
    if not result["payload_ready"]:
        raise ValueError("source-only artifact: verified Linux payload/native build is required")
    env = dict(os.environ, ARGUS_EXPERIMENT_INSTALL=result["variant"], ARGUS_WORKLOAD_BUILD_DIR=str(output / "build"))
    subprocess.run(["bash", str(output / "package/scripts/install.sh"), "--config", str(output / "environment.json")], env=env, check=True, timeout=120)
    return {"installed": True, "variant": result["variant"], "started": False,
            "next": "apply isolated entries on Server; resume/register target; start generated workload.py; inspect --live"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    subs = parser.add_subparsers(dest="action", required=True)
    render = subs.add_parser("render")
    render.add_argument("--variant", choices=VARIANTS, required=True)
    render.add_argument("--config", type=Path, required=True)
    render.add_argument("--output", type=Path, required=True)
    render.add_argument("--experiment-id", required=True)
    render.add_argument("--build-dir", type=Path)
    render.add_argument("--native-uid", type=int, default=0)
    render.add_argument("--static-credentials", type=Path)
    for action in ("inspect", "install"):
        command = subs.add_parser(action)
        command.add_argument("--output", type=Path, required=True)
        command.add_argument("--live" if action == "inspect" else "--execute-experiment", action="store_true")
    args = parser.parse_args()
    if args.action == "render":
        result = render_variant(args.config, args.variant, args.output, experiment_id=args.experiment_id,
                                build_dir=args.build_dir, native_uid=args.native_uid,
                                static_credentials=json.loads(args.static_credentials.read_text()) if args.static_credentials else None)
        result = {k: result[k] for k in ("variant", "payload_ready", "remote_acceptance")}
    elif args.action == "inspect":
        result = inspect_variant(args.output, live=args.live)
    else:
        result = install_variant(args.output, execute_experiment=args.execute_experiment)
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
